import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const indexPath = resolve(root, 'public/index.html');
let html = await readFile(indexPath, 'utf8');
const base = await readFile(resolve(root, 'references/customization-base/index.html'), 'utf8');
function section(text, start, end) {
  const a = text.indexOf(start), b = text.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error('Bloco não encontrado: ' + start);
  return [a, b];
}
const [baseStart, baseEnd] = section(base, '    <div class="cases">', '    <div class="gal-head">');
let featured = base.slice(baseStart, baseEnd);
featured = featured.replace('<div class="kick rv">Trabalho real</div>', '<div class="kick rv">Projetos em destaque</div>');
featured = featured.replace('<a class="btn btn-ghost" href="/site-do-jd">Ver como eu fiz</a>', '');
featured = featured.replace('<span class="case-k">Cliente</span>', '<span class="case-k">Projeto em destaque</span>');
featured = featured.replace('href="https://draanascatolin.com.br"', 'href="https://www.draanascatolin.com.br"');
featured = featured.replace('<h4>Dra. Ana Scatolin</h4>', '<h4 class="split">Dra. Ana Scatolin</h4>');
featured = featured.replaceAll('<h5>', '<h5 class="split">');
featured = featured.replace('<span class="feat-badge">', '<span class="feat-badge rv">');
featured = featured.replace('class="feat-name"', 'class="feat-name rv"');
featured = featured.replace('class="feat-who"', 'class="feat-who rv"');
featured = featured.replace('<p class="case-who">', '<p class="case-who rv">');
featured = featured.replace('<p>Um site claro', '<p class="rv">Um site claro');
const [currentStart, currentEnd] = section(html, '    <div class="cases">', '    <div class="gal-head">');
html = html.slice(0, currentStart) + featured + html.slice(currentEnd);
const [galleryStart, galleryEnd] = section(base, '    <div class="gallery" id="gallery">', '    <p class="gal-note">');
let gallery = base.slice(galleryStart, galleryEnd).replaceAll(' target="_blank" rel="noopener"', '');
gallery = gallery.replace('<b>Sabec° v3</b><span>site anterior da Sabec°</span>', '<b>Base de referência</b><span>versão anterior da Sabec</span>');
gallery = gallery.replace('<b>Liminar</b><span>advocacia</span>', '<b>Liminar</b><span>ensino em psicanálise</span>');
gallery = gallery.replace('Site de demonstração de escritório de advocacia', 'Site de demonstração de ensino em psicanálise');
const [a, b] = section(html, '    <div class="gallery" id="gallery">', '    <p class="gal-note">');
html = html.slice(0, a) + gallery + html.slice(b);
html = html.replace('Projetos conceito e demonstrações por segmento.', 'Demonstrações por segmento.');
html = html.replace(/<p class="gal-note">[\s\S]*?<\/p>/, '<p class="gal-note">Projetos e demonstrações de referência. O seu site recebe sua marca, seu conteúdo e suas fotos. Fale com <a href="https://instagram.com/gabrielholanda._" target="_blank" rel="noopener">@gabrielholanda._</a>.</p>');
html = html.replace('<link rel="icon" type="image/svg+xml" href="/assets/norte-autoral/favicon.svg">', '<link rel="icon" type="image/svg+xml" href="/assets/norte-autoral/favicon.svg?v=2">\n<link rel="icon" type="image/png" sizes="32x32" href="/assets/norte-autoral/favicon-32.png">\n<link rel="shortcut icon" href="/assets/norte-autoral/favicon.ico">');
await writeFile(indexPath, html, 'utf8');
console.log('JD, Ana e galeria da referência restaurados, com identidade Norte Autoral preservada.');
